"""Verify authorized reuse against untouched Mar de Ferro; record SHA-256 provenance."""
from pathlib import Path
import hashlib
import json
import argparse

ROOT = Path(__file__).resolve().parents[1]
ART = 'assets/art/combat/portugal/'
AUDIO = 'assets/audio/combat/'
COPIES = {
    ART+'paving-mar-de-ferro.png': 'assets/scenery/bruma-paving-tile-v1.png',
    ART+'bench-mar-de-ferro.png': 'assets/scenery/regional-bench-illustrated-v1.png',
    ART+'training-rack-mar-de-ferro.png': 'assets/scenery/bruma-training-rack-illustrated-v1.png',
    ART+'basic-attack.png': 'assets/skill_icons/duarte_0.png',
}
for name in ['swing','fast_swing','heavy_swing','heavy_hit','metal_hit','thrust','guard','parry','posture_break','footstep_wood','gesture_cover_windup','gesture_cover_impact','gesture_thrust_windup','gesture_thrust_impact','menu_confirm']:
    COPIES[AUDIO+name+'.wav'] = AUDIO+name+'.wav'

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source',type=Path,default=ROOT.parent/'jogo')
    args = parser.parse_args()
    entries = []
    for target, source in COPIES.items():
        local, original = (ROOT/target).read_bytes(), (args.source/source).read_bytes()
        if local != original:
            raise ValueError('Copied asset differs from source: '+target)
        entries.append({'local':target,'source':source,'sha256':hashlib.sha256(local).hexdigest()})
    result = {'source_project':str(args.source.resolve()),'source_modified':False,'copies':entries,
              'original_art':'prompts.json','original_audio':'assets/audio/combat/powder-training.wav; generated by tools/build_combat_audio.py',
              'heros_adventure_assets_added':False}
    (ROOT/ART/'reused-assets.json').write_text(json.dumps(result,indent=2)+'\n',encoding='utf-8')
    print(json.dumps({'verified_copies':len(entries),'source_modified':False}))

if __name__=='__main__': main()
